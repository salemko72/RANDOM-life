export function studioText(locale: 'en' | 'bs', value: string): string {
  if (locale === 'bs') {
 const missing=value.match(/^Missing (EN|BS) translation\.$/);if(missing)return `Nedostaje ${missing[1]==='EN'?'ENG':'BHS'} prevod.`;
 const review=value.match(/^(EN|BS) translation requires human review\.$/);if(review)return `${review[1]==='EN'?'ENG':'BHS'} prevod zahtijeva ljudski pregled.`;
 const alignment=value.match(/^(EN|BS) (ingredient names and units must match all ingredients|cooking steps must match the source|recommendation and genres are required|duration label is required|steps and equipment must match the source)\.$/);
 if(alignment)return `${alignment[1]==='EN'?'ENG':'BHS'}: provjeri kompletnost prevoda i podudaranje koraka, sastojaka i opreme sa osnovnim sadržajem.`;
 return value;
 }
  if (Object.prototype.hasOwnProperty.call(studioEnglish, value)) return studioEnglish[value];
  const published = value.match(/^Objavljeno: ([\s\S]*)\. Stavka je u Biblioteci; obrazac je spreman za novi unos\.$/);
  if (published) return `Published: ${published[1]}. The item is in the Library; the form is ready for a new entry.`;
  const editing = value.match(/^Uređuješ: ([\s\S]*) · (Nacrt|Na pregledu|Objavljeno)\. Za drugi recept koristi novi nacrt\.$/);
  if (editing) return `Editing: ${editing[1]} · ${studioEnglish[editing[2]]}. Start a new draft for another recipe.`;
  const copied = value.match(/^✓ Kopirano (.*)\. Spremno za ručno lijepljenje u ChatGPT; slanje nije automatsko\.$/);
  if (copied) return `✓ Copied ${copied[1]}. Ready to paste into ChatGPT manually; nothing is sent automatically.`;
  const prefix = value.match(/^(Ikona za |Oznaka: |JSON nije validan: )([\s\S]*)$/);
  if (prefix) return ({'Ikona za ': 'Icon for ', 'Oznaka: ': 'Tag: ', 'JSON nije validan: ': 'Invalid JSON: '} as Record<string, string>)[prefix[1]] + prefix[2];
  const atlas = value.match(/^Kopiraj listu za novi atlas \((\d+)\)$/);
  if (atlas) return `Copy list for a new atlas (${atlas[1]})`;
  const version = value.match(/^(Verzija|verzija) (\d+)$/);
  if (version) return `${version[1] === 'Verzija' ? 'Version' : 'version'} ${version[2]}`;
  const count = value.match(/^(\d+) stavki$/);
  if (count) return `${count[1]} items`;
  // Errors can combine publication checks. Translate only complete known UI sentences.
  return value.split('\n').map(line => line.split(/(?<=\.) (?=[A-ZČĆŠŽĐ])/).map(part => studioEnglish[part] ?? part).join(' ')).join('\n');
}

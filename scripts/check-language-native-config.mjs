import{execFileSync}from'node:child_process';
import{fileURLToPath}from'node:url';
import assert from'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url));
const config=JSON.parse(execFileSync(process.execPath,[root+'node_modules/expo/bin/cli','config','--type','introspect','--json'],{cwd:root+'apps/client',env:{...process.env,EXPO_NO_TELEMETRY:'1'},encoding:'utf8',maxBuffer:8*1024*1024}));
assert.deepEqual(config.ios.infoPlist.CFBundleLocalizations,['en','bs']);
const application=config._internal.modResults.android.manifest.manifest.application[0];
assert.equal(application.$['android:localeConfig'],'@xml/locales_config');
const activity=application.activity.find(value=>value.$['android:name']==='.MainActivity');
assert(activity.$['android:configChanges'].split('|').includes('locale'));
assert(activity.$['android:configChanges'].split('|').includes('layoutDirection'));
assert.equal(config.ios.supportsTablet,false);assert.equal(config.orientation,'portrait');
console.log('PASS generated iOS en/bs declarations, Android locale-config reference and foreground locale handling; iPhone-only/portrait preserved. No native build or physical QA.');
